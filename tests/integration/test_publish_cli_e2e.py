"""End-to-end `dqs publish preview` on a throwaway Postgres database (Phase 6a).

This is the real command path: persisted incident + root cause + impact +
`dq.fix_attempts` are read back by the CLI, the deterministic PR body/patch are
written to a temporary preview directory, and the publication row is stored in
`dq.publications`. The dev warehouse is never touched, and no GitHub client is
constructed because the command is dry-run only.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import pytest
from sqlalchemy import Engine, create_engine, text
from tests.helpers.publish import (
    F1_NEW,
    make_incident,
    make_plan,
    make_verification,
)
from typer.testing import CliRunner

from dqs import db as dbmod
from dqs.cli import app as dqs_app
from dqs.config import Settings
from dqs.incidents import build_drafts, persist_incidents, save_impact, save_root_cause
from dqs.verify.sandbox import persist_attempt

pytestmark = pytest.mark.integration

TEST_DB = "dqs_publish_cli"


@pytest.fixture
def cli_db(settings: Settings) -> Iterator[tuple[Settings, Engine]]:
    admin = create_engine(
        settings.rw_database_url.set(database="postgres"), isolation_level="AUTOCOMMIT"
    )
    try:
        with admin.connect() as conn:
            conn.exec_driver_sql(f'DROP DATABASE IF EXISTS "{TEST_DB}" WITH (FORCE)')
            conn.exec_driver_sql(f'CREATE DATABASE "{TEST_DB}"')
        test_settings = settings.model_copy(
            update={"pg_database": TEST_DB, "github_mode": "dry_run"}
        )
        dbmod.init_database(test_settings)
        engine = dbmod.make_rw_engine(test_settings)
        try:
            yield test_settings, engine
        finally:
            engine.dispose()
            with admin.connect() as conn:
                conn.exec_driver_sql(f'DROP DATABASE IF EXISTS "{TEST_DB}" WITH (FORCE)')
    finally:
        admin.dispose()


def _seed_verified_incident(engine: Engine) -> str:
    incident = make_incident()
    drafts = build_drafts(incident.violations)
    persisted = persist_incidents(engine, drafts)
    incident_id = persisted.created[0]
    save_root_cause(engine, incident_id, incident.root_cause or {})
    save_impact(engine, incident_id, incident.impact or {})
    plan = make_plan().model_copy(update={"incident_id": incident_id})
    persist_attempt(engine, plan, make_verification())
    return str(incident_id)


def test_cli_preview_writes_files_records_one_row_and_is_idempotent(
    cli_db: tuple[Settings, Engine],
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    test_settings, engine = cli_db
    incident_id = _seed_verified_incident(engine)

    # Redirect both the writer and the path the command prints, without
    # touching the real out/pr_previews directory.
    monkeypatch.setattr("dqs.cli.load_settings", lambda: test_settings)
    monkeypatch.setattr("dqs.publish.dry_run.OUTPUT_DIR", tmp_path)

    first = CliRunner().invoke(dqs_app, ["publish", "preview", incident_id])
    assert first.exit_code == 0, first.output
    assert "mode=dry_run kind=pr reused=False" in first.output

    md_path = tmp_path / f"{incident_id.replace('-', '')[:8]}.md"
    patch_path = md_path.with_suffix(".patch")
    assert md_path.is_file() and patch_path.is_file()
    body = md_path.read_text(encoding="utf-8")
    patch = patch_path.read_text(encoding="utf-8")
    assert "## Verification" in body
    assert "Generated by dqs" in body
    assert f"+{F1_NEW}" in patch

    with engine.connect() as conn:
        rows = conn.execute(text("SELECT incident_id, kind, mode, url FROM dq.publications")).all()
    assert len(rows) == 1
    assert str(rows[0][0]) == incident_id
    assert (rows[0][1], rows[0][2]) == ("pr", "dry_run")
    assert rows[0][3] == md_path.resolve().as_uri()

    body_before = md_path.read_bytes()
    second = CliRunner().invoke(dqs_app, ["publish", "preview", incident_id])
    assert second.exit_code == 0, second.output
    assert "mode=dry_run kind=pr reused=True" in second.output
    assert "reused=False" not in second.output

    with engine.connect() as conn:
        count = conn.execute(text("SELECT count(*) FROM dq.publications")).scalar_one()
    assert count == 1
    assert md_path.read_bytes() == body_before
