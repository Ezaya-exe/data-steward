"""Benchmark page: pick a results file, show provenance and the real report.

Why not re-implement the tables here: `dqs.bench.report.render_markdown` already
renders the overall and per-fault-kind tables with exact numerators, n and 95%
Wilson intervals. Reusing it means the UI cannot drift from `latest.md` or the
CLI console. The page adds only the caveats a human must see before quoting a
number: pilot size, early stop, infra errors and a dirty working tree.
"""

from __future__ import annotations

import common
import streamlit as st

from dqs.errors import DqsError

common.configure_page("Benchmark")
settings, database, engine = common.sidebar_context()
service = common.get_service()

st.title("Benchmark results")
st.caption(f"Directory: benchmarks/results/ · database selector: {database} (unused here)")

try:
    files = service.list_benchmark_files(common.BENCHMARK_RESULTS_DIR)
except DqsError as exc:
    st.error(f"Could not list benchmark results: {common.error_text(exc)}")
    files = []

if not files:
    st.info(
        "No benchmark results found. Run the benchmark with `dqs bench run` "
        "after the preflight passes."
    )
    st.stop()

labels = {
    f"{item.name} · {item.size_bytes // 1024} KiB · {common.format_ts(item.modified_at)}": item.name
    for item in files
}
picked = st.selectbox("Results file", list(labels), key="benchmark_file")
name = labels[picked]

try:
    view = service.benchmark_view(name, common.BENCHMARK_RESULTS_DIR)
except DqsError as exc:
    st.error(f"Could not read {name}: {common.error_text(exc)}")
    st.stop()

for note in view.notes:
    st.warning(note)

scenario_col, infra_col, kind_col = st.columns(3)
scenario_col.metric("Scenario records", view.scenario_count)
infra_col.metric("Infrastructure errors", view.infra_errors)
kind_col.metric("Fault kinds", len(view.fault_kinds))

st.subheader("Provenance")
st.dataframe(
    [{"Field": row.label, "Value": row.value} for row in view.metadata],
    hide_index=True,
    width="stretch",
)

st.divider()
st.subheader("Report")
st.caption(
    "Generated by the existing `dqs bench report` code: exact numerators, n, and "
    "95% Wilson confidence intervals. Infrastructure errors are excluded from denominators."
)
st.markdown(view.report_markdown, unsafe_allow_html=False)
