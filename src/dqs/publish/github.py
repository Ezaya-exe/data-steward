logger = logging.getLogger(__name__)

LABEL_NAME: Final = "data-quality"
LABEL_COLOR: Final = "0e8a16"
LABEL_DESCRIPTION: Final = "Generated by the dqs data-quality steward; human review required."
BRANCH_PATTERN: Final = re.compile(r"^dqs/incident-[0-9a-f]{8}$")
REPO_PATTERN: Final = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
MAX_TITLE_CHARS: Final = 200


class RemoteFile(NamedTuple):
    """A file read from GitHub: decoded UTF-8 text plus the blob sha."""

    text: str
    sha: str


class GitHubClient(Protocol):
    """The narrow GitHub surface the live publisher is allowed to use."""

    def base_sha(self, branch: str) -> str: ...

    def branch_exists(self, branch: str) -> bool: ...

    def read_file(self, path: str, ref: str) -> RemoteFile | None: ...

    def create_branch(self, branch: str, sha: str) -> None: ...

    def put_file(
        self, path: str, content: str, message: str, branch: str, sha: str | None
    ) -> None: ...

    def pull_for_branch(self, branch: str) -> tuple[int, str] | None: ...

    def create_pull(self, *, title: str, body: str, head: str, base: str) -> tuple[int, str]: ...

    def ensure_label(self, name: str) -> None: ...

    def add_labels(self, number: int, labels: Sequence[str]) -> None: ...

    def create_issue(self, *, title: str, body: str, labels: Sequence[str]) -> tuple[int, str]: ...

    def find_issue(self, marker: str) -> tuple[int, str] | None: ...


class GitHubPublisher(Publisher):
    """Live publisher: branch, commit changed files, open PR/issue, label."""

    mode = PublicationMode.LIVE

    def __init__(
        self,
        client: GitHubClient,
        store: PublicationStore,
        *,
        repo_slug: str,
        base_branch: str,
        settings: Settings | None = None,
    ) -> None:
        super().__init__(store)
        self.client = client
        self.repo_slug = repo_slug
        self.base_branch = base_branch
        self.settings = settings

    def _create_pr(
        self,
        plan: FixPlan,
        incident: Incident,
        verification: VerificationResult,
        approval: ApprovalDecision,
        *,
        retry: bool,
    ) -> PublicationResult:
        try:
            patches = build_file_patches(plan.edits)
        except FixPlanError as exc:
            raise PublicationError(f"cannot build the commit diff: {exc}") from exc

        body = render_pr_body(
            plan, incident, verification, patches, approval=approval, settings=self.settings
        )
        title = pr_title(plan, incident)
        branch = branch_name(incident.incident_id)
        if branch == self.base_branch:
            raise PublicationError("refusing to commit to the configured base branch")
        message = commit_message(plan, incident)

        try:
            existing = self.client.pull_for_branch(branch)
            if existing is None:
                # A commit based on a stale checkout would silently revert
                # someone else's change. Compare every target file with the
                # base branch before creating the branch or writing anything.
                _assert_base_matches(self.client, patches, self.base_branch)
                if not self.client.branch_exists(branch):
                    self.client.create_branch(branch, self.client.base_sha(self.base_branch))
                for patch in patches:
                    remote = self.client.read_file(patch.path, branch)
                    self.client.put_file(
                        patch.path,
                        patch.new_text,
                        message,
                        branch,
                        remote.sha if remote is not None else None,
                    )
                number, url = self.client.create_pull(
                    title=title, body=body, head=branch, base=self.base_branch
                )
                reused = False
            else:
                number, url = existing
                reused = True

            # The label step is idempotent and also repairs a run that crashed
            # after opening the PR but before labelling it.
            self.client.ensure_label(LABEL_NAME)
            self.client.add_labels(number, [LABEL_NAME])
        except PublicationError:
            raise
        except Exception as exc:
            raise PublicationError(
                "GitHub publish failed: " + _redacted_error(exc, self.settings)
            ) from exc

        return PublicationResult(
            incident_id=incident.incident_id,
            kind=PublicationKind.PR,
            mode=PublicationMode.LIVE,
            url=url,
            reused=reused,
        )

    def _create_issue(
        self,
        issue_md: IssueDraft | str,
        incident: Incident,
        approval: ApprovalDecision,
        *,
        retry: bool,
    ) -> PublicationResult:
        content = issue_md.markdown if isinstance(issue_md, IssueDraft) else issue_md
        secrets = settings_secrets(self.settings) if self.settings is not None else []
        title = _issue_title(issue_md, incident)
        marker = issue_marker(incident.incident_id)
        body = sanitize_document(f"Incident marker: {marker}\n\n{content}", secrets=secrets)

        try:
            existing = self.client.find_issue(marker) if retry else None
            if existing is not None:
                return PublicationResult(
                    incident_id=incident.incident_id,
                    kind=PublicationKind.ISSUE,
                    mode=PublicationMode.LIVE,
                    url=existing[1],
                    reused=True,
                )
            self.client.ensure_label(LABEL_NAME)
            _number, url = self.client.create_issue(title=title, body=body, labels=[LABEL_NAME])
        except PublicationError:
            raise
        except Exception as exc:
            raise PublicationError(
                "GitHub issue creation failed: " + _redacted_error(exc, self.settings)
            ) from exc

        return PublicationResult(
            incident_id=incident.incident_id,
            kind=PublicationKind.ISSUE,
            mode=PublicationMode.LIVE,
            url=url,
        )


class PyGithubClient:
    """Adapter over PyGithub 2.10.0 (signatures checked against the install)."""

    def __init__(self, *, token: str, repo: str) -> None:
        self._github = Github(token)
        self._repo = self._github.get_repo(repo)

    def base_sha(self, branch: str) -> str:
        return str(self._repo.get_branch(branch).commit.sha)

    def branch_exists(self, branch: str) -> bool:
        try:
            self._repo.get_branch(branch)
        except UnknownObjectException:
            return False
        return True

    def read_file(self, path: str, ref: str) -> RemoteFile | None:
        try:
            content = self._repo.get_contents(path, ref=ref)
        except UnknownObjectException:
            return None
        if isinstance(content, list):
            raise PublicationError(f"expected a file at {path!r}, found a directory")
        return RemoteFile(
            text=content.decoded_content.decode("utf-8"),
            sha=str(content.sha),
        )

    def create_branch(self, branch: str, sha: str) -> None:
        self._repo.create_git_ref(ref=f"refs/heads/{branch}", sha=sha)

    def put_file(self, path: str, content: str, message: str, branch: str, sha: str | None) -> None:
        if sha is None:
            self._repo.create_file(path=path, message=message, content=content, branch=branch)
        else:
            self._repo.update_file(
                path=path, message=message, content=content, sha=sha, branch=branch
            )

    def pull_for_branch(self, branch: str) -> tuple[int, str] | None:
        for pull in self._repo.get_pulls(state="open"):
            if pull.head.ref == branch:
                return int(pull.number), str(pull.html_url)
        return None

    def create_pull(self, *, title: str, body: str, head: str, base: str) -> tuple[int, str]:
        pull = self._repo.create_pull(base=base, head=head, title=title, body=body)
        return int(pull.number), str(pull.html_url)

    def ensure_label(self, name: str) -> None:
        try:
            self._repo.get_label(name)
        except UnknownObjectException:
            self._repo.create_label(name=name, color=LABEL_COLOR, description=LABEL_DESCRIPTION)

    def add_labels(self, number: int, labels: Sequence[str]) -> None:
        self._repo.get_pull(number).add_to_labels(*labels)

    def create_issue(self, *, title: str, body: str, labels: Sequence[str]) -> tuple[int, str]:
        issue = self._repo.create_issue(title=title, body=body, labels=list(labels))
        return int(issue.number), str(issue.html_url)

    def find_issue(self, marker: str) -> tuple[int, str] | None:
        for issue in self._repo.get_issues(state="open"):
            if marker in (issue.title or "") or marker in (issue.body or ""):
                return int(issue.number), str(issue.html_url)
        return None


def issue_marker(incident_id: uuid.UUID) -> str:
    """Deterministic body marker used to recover a crashed issue publication."""
    return f"dqs-incident-{incident_id.hex[:8]}"


def _assert_base_matches(
    client: GitHubClient, patches: Sequence[FilePatch], base_branch: str
) -> None:
    """Refuse to commit when the checkout differs from the base branch."""
    for patch in patches:
        remote = client.read_file(patch.path, base_branch)
        if remote is None:
            raise PublicationError(
                f"{patch.path} does not exist on {base_branch}; push local commits first"
            )
        if remote.text != patch.old_text:
            raise PublicationError(
                f"{patch.path} on {base_branch} does not match the local checkout; "
                "push local commits first"
            )


def branch_name(incident_id: uuid.UUID) -> str:
    """`dqs/incident-<short_id>`, validated before any API call."""
    return validate_branch_name(f"dqs/incident-{incident_id.hex[:8]}")


def validate_branch_name(name: str) -> str:
    if not BRANCH_PATTERN.match(name):
        raise PublicationError(
            f"unsafe branch name {name!r}; expected dqs/incident-<8 lowercase hex>"
        )
    return name


def commit_message(plan: FixPlan, incident: Incident) -> str:
    """Code-only commit message: no model prose can enter git history."""
    return (
        f"dqs: fix {plan.category.value} in {plan.affected_table} "
        f"(incident {incident.incident_id.hex[:8]})"
    )


def build_publisher(
    settings: Settings,
    *,
    store: PublicationStore,
    github_client: GitHubClient | None = None,
    output_dir: Path | None = None,
) -> Publisher:
    """Choose dry-run or live, failing closed when live is misconfigured."""
    if settings.github_mode == "live":
        missing = [
            name
            for name, value in (
                ("GITHUB_TOKEN", settings.github_token),
                ("GITHUB_REPO", settings.github_repo),
            )
            if not value.strip()
        ]
        if missing:
            raise PublicationError(
                "GITHUB_MODE=live requires " + " and ".join(missing) + " to be set"
            )
        if not REPO_PATTERN.match(settings.github_repo):
            raise PublicationError("GITHUB_REPO must look like 'owner/repo'")
        client = github_client
        if client is None:
            try:
                client = PyGithubClient(token=settings.github_token, repo=settings.github_repo)
            except Exception as exc:
                raise PublicationError(
                    "could not create the GitHub client: " + _redacted_error(exc, settings)
                ) from exc
        return GitHubPublisher(
            client,
            store,
            repo_slug=settings.github_repo,
            base_branch=settings.github_base_branch,
            settings=settings,
        )

    from dqs.publish.dry_run import OUTPUT_DIR, DryRunPublisher

    return DryRunPublisher(
        store,
        output_dir=output_dir or OUTPUT_DIR,
        settings=settings,
    )


def _issue_title(issue_md: IssueDraft | str, incident: Incident) -> str:
    if isinstance(issue_md, IssueDraft):
        raw = issue_md.title
    else:
        first = next((line for line in issue_md.splitlines() if line.strip()), "")
        raw = first.lstrip("#").strip()
    raw = raw or f"[data-quality] incident {incident.incident_id.hex[:8]}"
    return sanitize_text(raw, limit=MAX_TITLE_CHARS)


def _redacted_error(exc: BaseException, settings: Settings | None) -> str:
    secrets = settings_secrets(settings) if settings is not None else []
    return redact_secrets(f"{type(exc).__name__}: {exc}", secrets=secrets)


