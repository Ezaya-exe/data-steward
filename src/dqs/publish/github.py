"""Live GitHub publisher (docs/ARCHITECTURE.md §12).

Why a client protocol: live mode must be exercised in tests without a network
call or a token. `GitHubClient` is the small typed surface the publisher needs;
`PyGithubClient` adapts PyGithub 2.10.0 (the installed version), and tests use an
in-memory fake. The publisher itself contains no PyGithub calls, so the safety
properties (branch name, target branch, never merge/force) are testable.

Safety by construction and by check:
- the branch is `dqs/incident-<8 hex>` and is validated against a regex;
- it must differ from `GITHUB_BASE_BRANCH`; every file write passes that branch;
- the client protocol has no merge, force-push, or base-branch write method;
- live mode fails closed unless `GITHUB_MODE=live` AND token AND repo are set.
"""

from __future__ import annotations

