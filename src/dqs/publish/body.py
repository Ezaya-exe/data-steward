"""Deterministic PR body template (docs/ARCHITECTURE.md §12).

Why a template and not an LLM: the body is the artifact a reviewer approves.
Every sentence is either a stored typed fact (incident, root cause, impact,
verification), a pure computation (diff stats), or fixed policy text. The only
free-form inputs are sanitized before they touch the document, so model prose
and hostile source data cannot add structure, ping users, or link elsewhere.

`render_pr_body` is pure: same inputs -> identical Markdown. The publisher
writes that text unchanged to the preview file and the GitHub PR.
"""

from __future__ import annotations

import json
import re
from collections.abc import Sequence
from pathlib import PurePosixPath
from typing import Final

from pydantic import ValidationError

from dqs.agents.issue_builder import NEXT_STEPS
from dqs.agents.llm import settings_secrets
from dqs.config import Settings
from dqs.models.fix import CriterionResult, FixPlan, VerificationResult
from dqs.models.impact import ImpactReport
from dqs.models.incident import Incident
from dqs.models.root_cause import RootCause
from dqs.publish.base import ApprovalDecision
from dqs.publish.diff import FilePatch
from dqs.publish.sanitize import (
    MAX_DOCUMENT_CHARS,
    fenced,
    sanitize_block,
    sanitize_text,
)

REQUIRED_SECTIONS: Final = (
    "## Incident summary",
    "## Root cause",
    "## Evidence",
    "## Impact",
    "## Diff summary",
    "## Verification",
    "## Risk",
    "## Follow-ups",
)
REVIEW_FOOTER: Final = "Generated by dqs — human review required."
MAX_LIST_ITEMS: Final = 20
MAX_PATCH_CHARS: Final = 8_000
MAX_TITLE_CHARS: Final = 200
_SAFE_NAME: Final = re.compile(r"[^a-z0-9_]+")


def render_pr_body(
    plan: FixPlan,
    incident: Incident,
    verification: VerificationResult,
    patches: Sequence[FilePatch],
    *,
    approval: ApprovalDecision | None = None,
    settings: Settings | None = None,
) -> str:
    """Render the full PR body from stored, verified facts."""
    secrets = settings_secrets(settings) if settings is not None else []
    root_cause = _root_cause(incident)
    impact = _impact(incident)

    lines: list[str] = [
        f"# {pr_title(plan, incident)}",
        "",
    ]
    lines.extend(_incident_section(incident, approval, secrets))
    lines.extend(_root_cause_section(root_cause, secrets))
    lines.extend(_evidence_section(root_cause, secrets))
    lines.extend(_impact_section(impact, secrets))
    lines.extend(_diff_section(plan, patches, secrets))
    lines.extend(_verification_section(verification, secrets))
    lines.extend(_risk_section(plan, secrets))
    lines.extend(_follow_ups_section(plan, impact, secrets))
    lines.extend(
        [
            f"> Fingerprint: `{sanitize_text(incident.fingerprint, secrets=secrets)}`",
            "> " + REVIEW_FOOTER,
            "",
        ]
    )

    body = "\n".join(lines)
    if len(body) > MAX_DOCUMENT_CHARS:
        body = body[: MAX_DOCUMENT_CHARS - 32] + "\n\n…[body truncated]\n"
    return body


def pr_title(plan: FixPlan, incident: Incident) -> str:
    """Human-readable conventional-commit title built from code-only fields."""
    scope = _title_scope(plan)
    action = _title_action(plan)
    title = f"fix({scope}): {action} (incident {incident.incident_id.hex[:8]})"
    if len(title) > MAX_TITLE_CHARS:
        title = title[: MAX_TITLE_CHARS - 1].rstrip() + "…"
    return title


def _title_scope(plan: FixPlan) -> str:
    names: list[str] = []
    for edit in plan.edits:
        stem = PurePosixPath(edit.path.replace("\\", "/")).stem.lower()
        safe = _SAFE_NAME.sub("_", stem).strip("_")
        if safe and safe not in names:
            names.append(safe)
    return ",".join(names) or "dbt"


def _title_action(plan: FixPlan) -> str:
    column = plan.affected_columns[0] if plan.affected_columns else ""
    table = plan.affected_table
    if plan.category.value == "SOURCE_COLUMN_RENAMED" and column:
        return f"read renamed column {column} from {table}"
    if plan.category.value == "SOURCE_TYPE_CHANGED" and column:
        return f"cast {column} to the published type from {table}"
    if plan.category.value == "DUPLICATE_RECORDS":
        return f"deduplicate {table} rows by primary key"
    if column:
        return f"repair {column} in {table}"
    return f"repair {table}"


def _incident_section(
    incident: Incident, approval: ApprovalDecision | None, secrets: Sequence[str]
) -> list[str]:
    # The stored status is frequently still "investigating" at publish time; the
    # approval object is the truth the reviewer needs to see.
    state = (
        approval.label
        if approval is not None
        else f"{incident.status.value} (no approval recorded in this preview)"
    )
    lines = [
        "## Incident summary",
        "",
        f"- **Incident:** `{incident.incident_id}`",
        f"- **Severity:** {incident.severity.value}",
        f"- **Status:** {state}",
        f"- **Table:** `{sanitize_text(incident.table or 'unknown', secrets=secrets)}`",
        f"- **Batches:** {_inline_list(incident.batches, secrets)}",
        f"- **Detected:** {incident.created_at.isoformat()}",
        f"- **Last seen:** {incident.updated_at.isoformat()}",
        f"- **Violations:** {len(incident.violations)}",
        "",
    ]
    if incident.violations:
        lines.extend(["### Detected violations", ""])
        for violation in incident.violations[:MAX_LIST_ITEMS]:
            column = (
                f" column `{sanitize_text(violation.column, secrets=secrets)}`"
                if violation.column
                else ""
            )
            batch = (
                f" in `{sanitize_text(violation.batch_id, secrets=secrets)}`"
                if violation.batch_id
                else ""
            )
            lines.append(
                f"- `{sanitize_text(violation.check, secrets=secrets)}` "
                f"({violation.severity.value}) on "
                f"`{sanitize_text(violation.table or 'unknown table', secrets=secrets)}`"
                f"{column}{batch}: {sanitize_text(violation.message, secrets=secrets)}"
            )
        if len(incident.violations) > MAX_LIST_ITEMS:
            lines.append(f"- … and {len(incident.violations) - MAX_LIST_ITEMS} more")
        lines.append("")
    return lines


def _root_cause_section(root_cause: RootCause | None, secrets: Sequence[str]) -> list[str]:
    lines = ["## Root cause", ""]
    if root_cause is None:
        lines.extend(["No valid root-cause record is stored for this incident.", ""])
        return lines
    table = sanitize_text(root_cause.affected_table or "not narrowed", secrets=secrets)
    lines.extend(
        [
            f"- **Category:** `{root_cause.category.value}`",
            f"- **Confidence:** {root_cause.confidence:.2f} (model-reported, uncalibrated)",
            f"- **Affected table:** `{table}`",
            f"- **Affected columns:** {_inline_list(root_cause.affected_columns, secrets)}",
            "",
            sanitize_text(root_cause.summary, secrets=secrets),
            "",
        ]
    )
    if root_cause.hypotheses_rejected:
        lines.extend(["### Hypotheses rejected", ""])
        for hypothesis in root_cause.hypotheses_rejected[:MAX_LIST_ITEMS]:
            lines.append(f"- {sanitize_text(hypothesis, secrets=secrets)}")
        lines.append("")
    return lines


def _evidence_section(root_cause: RootCause | None, secrets: Sequence[str]) -> list[str]:
    lines = ["## Evidence", ""]
    evidence = root_cause.evidence if root_cause is not None else []
    if not evidence:
        lines.extend(["No evidence is recorded.", ""])
        return lines
    for index, item in enumerate(evidence[:MAX_LIST_ITEMS], start=1):
        lines.extend(
            [
                f"### Evidence {index}: `{sanitize_text(item.tool, secrets=secrets)}`",
                "",
                fenced(sanitize_block(item.finding, secrets=secrets)),
                "",
            ]
        )
    if len(evidence) > MAX_LIST_ITEMS:
        lines.extend([f"… and {len(evidence) - MAX_LIST_ITEMS} more evidence items.", ""])
    return lines


def _impact_section(impact: ImpactReport | None, secrets: Sequence[str]) -> list[str]:
    lines = ["## Impact", ""]
    if impact is None:
        lines.extend(["No valid impact report is stored for this incident.", ""])
        return lines
    source_table = sanitize_text(impact.source_table or "warehouse-wide", secrets=secrets)
    lines.extend(
        [
            f"- **Scope:** {impact.scope.value}",
            f"- **Source table:** `{source_table}`",
            f"- **Column:** {_inline_list([impact.column] if impact.column else [], secrets)}",
            f"- **Blast radius score:** {impact.blast_radius_score}",
            "",
            _impact_sentence(impact, secrets),
            "",
        ]
    )
    if impact.affected_models:
        lines.extend(
            [
                "### Affected models",
                "",
                "| model | layer | distance | direct column lineage |",
                "|---|---|---|---|",
            ]
        )
        # Every downstream model, not a sample: the summary sentence above
        # counts the same list, so the prose and the table cannot disagree.
        for model in impact.affected_models:
            lines.append(
                f"| `{_cell(model.name, secrets)}` | {_cell(model.layer, secrets)} | "
                f"{model.distance} | {'yes' if model.referencing_column else 'no'} |"
            )
        lines.append("")
    if impact.affected_exposures:
        lines.extend(
            [
                "### Affected exposures and owners",
                "",
                "| exposure | owner | maturity |",
                "|---|---|---|",
            ]
        )
        for exposure in impact.affected_exposures[:MAX_LIST_ITEMS]:
            owner = _cell(exposure.owner or "unowned", secrets)
            lines.append(
                f"| `{_cell(exposure.name, secrets)}` | {owner} "
                f"| {_cell(exposure.maturity, secrets)} |"
            )
        lines.append("")
    if impact.failing_tests:
        lines.extend(["### Failing dbt nodes (stored run record)", ""])
        for node in impact.failing_tests[:MAX_LIST_ITEMS]:
            batch = (
                f" in `{sanitize_text(node.batch_id, secrets=secrets)}`" if node.batch_id else ""
            )
            lines.append(
                f"- `{sanitize_text(node.name, secrets=secrets)}` "
                f"({sanitize_text(node.status, secrets=secrets)}){batch}"
            )
        lines.append("")
    return lines


def _impact_sentence(impact: ImpactReport, secrets: Sequence[str]) -> str:
    """One sentence computed from exactly the rows rendered below it."""
    models = len(impact.affected_models)
    direct = sum(1 for model in impact.affected_models if model.referencing_column)
    exposures = len(impact.affected_exposures)
    owners = sorted({exposure.owner for exposure in impact.affected_exposures if exposure.owner})
    target = (impact.source_table or "the warehouse") + (
        f".{impact.column}" if impact.column else ""
    )
    model_part = (
        f"{models} downstream model{'s' if models != 1 else ''} "
        f"({direct} with direct column lineage)"
    )
    if exposures:
        owner_part = f", owners: {', '.join(owners)}" if owners else ", unowned"
        exposure_part = f"{exposures} exposure{'s' if exposures != 1 else ''}{owner_part}"
        clause = f"{model_part} and {exposure_part} are affected"
    else:
        clause = f"{model_part} {'are' if models != 1 else 'is'} affected"
    if models == 0 and exposures == 0:
        clause = "No downstream model or exposure is affected"
    return sanitize_text(f"{clause} by the change to {target}.", secrets=secrets)


def _diff_section(plan: FixPlan, patches: Sequence[FilePatch], secrets: Sequence[str]) -> list[str]:
    lines = [
        "## Diff summary",
        "",
        sanitize_text(plan.summary, secrets=secrets),
        "",
    ]
    if not patches:
        lines.extend(["No file changes.", ""])
        return lines
    added = sum(patch.added for patch in patches)
    removed = sum(patch.removed for patch in patches)
    lines.extend(
        [
            f"Files changed: {len(patches)} · +{added} / −{removed}",
            "",
            "| file | added | removed |",
            "|---|---|---|",
        ]
    )
    for patch in patches:
        lines.append(f"| `{_cell(patch.path, secrets)}` | {patch.added} | {patch.removed} |")
    lines.extend(
        [
            "",
            "```diff",
            sanitize_block(
                "".join(patch.patch for patch in patches), limit=MAX_PATCH_CHARS, secrets=secrets
            ),
            "```",
            "",
            "### Rationale",
            "",
            sanitize_text(plan.rationale, secrets=secrets),
            "",
            f"- **Expected effect:** {sanitize_text(plan.expected_effect, secrets=secrets)}",
            "",
        ]
    )
    return lines


def _verification_section(verification: VerificationResult, secrets: Sequence[str]) -> list[str]:
    by_name = {criterion.name: criterion for criterion in verification.criteria}
    sandbox = sanitize_text(verification.sandbox_schema or "not recorded", secrets=secrets)
    exit_code = (
        verification.dbt_exit_code if verification.dbt_exit_code is not None else "not recorded"
    )
    lines = [
        "## Verification",
        "",
        f"- **Verdict:** {'PASS' if verification.passed else 'FAIL'}",
        f"- **Sandbox schema:** `{sandbox}`",
        f"- **Sandbox build:** {_criterion_verdict(by_name.get('dbt_build'))}",
        f"- **dbt tests:** {_criterion_verdict(by_name.get('dbt_tests'))}",
        f"- **Contract conformance:** {_criterion_verdict(by_name.get('contract_conformance'))}",
        f"- **Row preservation:** {_criterion_verdict(by_name.get('row_preservation'))}",
        f"- **dbt exit code:** {exit_code}",
        f"- **Duration:** {verification.duration_s:.2f} s",
        f"- **Contract tables checked:** {_inline_list(verification.contract_tables, secrets)}",
        f"- **Failed criteria:** {_inline_list(verification.failed_criteria, secrets)}",
        "",
    ]

    lines.extend(
        [
            "### Criteria",
            "",
            "| criterion | verdict | observed | detail |",
            "|---|---|---|---|",
        ]
    )
    if not verification.criteria:
        lines.append("| none recorded | — | — | — |")
    # Every criterion, including the targeted check: a reviewer must be able to
    # see the observed values that justified the verdict.
    for criterion in verification.criteria:
        observed = (
            json.dumps(criterion.observed, sort_keys=True, default=str)
            if criterion.observed
            else "—"
        )
        lines.append(
            f"| `{_cell(criterion.name, secrets)}` | "
            f"{'PASS' if criterion.passed else 'FAIL'} | "
            f"{_cell(observed, secrets)} | "
            f"{_cell(criterion.detail or '—', secrets)} |"
        )
    lines.append("")

    if verification.row_counts:
        lines.extend(["### Row counts", "", "| table | rows |", "|---|---|"])
        for table in sorted(verification.row_counts):
            lines.append(f"| `{_cell(table, secrets)}` | {verification.row_counts[table]} |")
        lines.append("")
    else:
        lines.extend(["### Row counts", "", "No row counts were recorded.", ""])

    lines.extend(["### dbt excerpt", ""])
    if verification.dbt_log_excerpt:
        lines.extend([fenced(sanitize_block(verification.dbt_log_excerpt, secrets=secrets)), ""])
    else:
        lines.extend(["No dbt excerpt was recorded.", ""])
    return lines


def _risk_section(plan: FixPlan, secrets: Sequence[str]) -> list[str]:
    return [
        "## Risk",
        "",
        sanitize_block(plan.risk, secrets=secrets),
        "",
    ]


def _follow_ups_section(
    plan: FixPlan, impact: ImpactReport | None, secrets: Sequence[str]
) -> list[str]:
    """Operator follow-ups: owner notification, contract decision, playbook."""
    table = sanitize_text(plan.affected_table, secrets=secrets)
    owners = (
        sorted(
            {
                exposure.owner
                for exposure in (impact.affected_exposures if impact is not None else [])
                if exposure.owner
            }
        )
        if impact is not None
        else []
    )
    lines = ["## Follow-ups", ""]
    if owners:
        lines.append(f"- Notify the source owner ({', '.join(owners)}) about the `{table}` change.")
    else:
        lines.append(f"- Notify the source owner of `{table}` about this change.")
    lines.append(f"- Decide whether the published contract for `{table}` needs updating.")
    for step in NEXT_STEPS.get(plan.category, ()):
        lines.append(f"- {sanitize_text(step, secrets=secrets)}")
    lines.append("")
    return lines


def _criterion_verdict(criterion: CriterionResult | None) -> str:
    if criterion is None:
        return "not recorded"
    return "PASS" if criterion.passed else "FAIL"


def _inline_list(values: Sequence[str], secrets: Sequence[str]) -> str:
    if not values:
        return "none"
    shown = ", ".join(f"`{sanitize_text(value, secrets=secrets)}`" for value in values)
    return shown


def _cell(value: str, secrets: Sequence[str]) -> str:
    # A raw `|` would create an extra table column and break the layout.
    return sanitize_text(value, secrets=secrets).replace("|", r"\|")


def _root_cause(incident: Incident) -> RootCause | None:
    if incident.root_cause is None:
        return None
    try:
        return RootCause.model_validate(incident.root_cause)
    except ValidationError:
        return None


def _impact(incident: Incident) -> ImpactReport | None:
    if incident.impact is None:
        return None
    try:
        return ImpactReport.model_validate(incident.impact)
    except ValidationError:
        return None


__all__ = ["REQUIRED_SECTIONS", "REVIEW_FOOTER", "pr_title", "render_pr_body"]
